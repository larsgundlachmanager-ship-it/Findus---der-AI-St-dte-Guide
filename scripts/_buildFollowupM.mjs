const SENIOR_MAP = ['spa_value', 'anti_party', 'family'];

function fixVibes(arr) {
  const out = [];
  for (const v of arr || []) {
    if (v === 'senior') out.push(...SENIOR_MAP);
    else if (ALLOWED.has(v)) out.push(v);
  }
  return [...new Set(out)];
}

function conf(c) {
  const s = String(c || 'high').toLowerCase();
  if (s.includes('live')) return 'medium';
  if (s.startsWith('hoch') || s === 'high') return 'high';
  if (s.startsWith('nied') || s === 'low') return 'low';
  return 'medium';
}

function specials(s) {
  if (Array.isArray(s)) return s;
  if (typeof s === 'string' && s.trim()) return [s.trim()];
  return [];
}

